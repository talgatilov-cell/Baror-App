"""Static / repo-level facts (run from anywhere). Read-only on the real repo."""
import ast, os, subprocess, tempfile, shutil, re, sys
REPO = "/home/claude/talgatilov-cell/baror-app"
src = open(f"{REPO}/app.py", encoding="utf-8").read()
tree = ast.parse(src)
print("lines:", len(src.splitlines()), " defs:", [n.name for n in tree.body if isinstance(n, ast.FunctionDef)], " classes:", sum(isinstance(n, ast.ClassDef) for n in tree.body))
print("bare except lines:", [n.lineno for n in ast.walk(tree) if isinstance(n, ast.ExceptHandler) and n.type is None])
print("use_container_width lines:", [i+1 for i, l in enumerate(src.splitlines()) if "use_container_width" in l])
print("image/jpg MIME lines:", [i+1 for i, l in enumerate(src.splitlines()) if "image/jpg" in l])
nums = sorted({n.value for n in ast.walk(tree) if isinstance(n, ast.Constant) and isinstance(n.value, int) and not isinstance(n.value, bool) and n.value > 10})
print("magic ints >10:", nums)
print("gender literal 'זכר' occurrences:", src.count('"זכר"'))
# .gitignore encoding + effect, in a throw-away repo (real repo untouched)
raw = open(f"{REPO}/.gitignore", "rb").read()
print(".gitignore first bytes:", raw[:4], "-> UTF-16 LE BOM" if raw[:2] == b"\xff\xfe" else "")
t = tempfile.mkdtemp()
subprocess.run(["git", "init", "-q", t])
shutil.copy(f"{REPO}/.gitignore", t); open(f"{t}/users.json", "w").write('{"a@b.c": {"password": "1234"}}')
os.makedirs(f"{t}/.venv"); open(f"{t}/.venv/x", "w").write("x")
r = subprocess.run(["git", "-C", t, "status", "--porcelain", "-uall"], capture_output=True, text=True)
print("git status with ORIGINAL .gitignore:\n" + r.stdout)
r = subprocess.run(["git", "-C", REPO, "check-ignore", "-v", "users.json"], capture_output=True, text=True)
print("check-ignore users.json in real repo -> rc", r.returncode, "(1 = NOT ignored)")
shutil.copy("/home/claude/audit/scratch/bugs/fixed/.gitignore", t)
r = subprocess.run(["git", "-C", t, "status", "--porcelain", "-uall"], capture_output=True, text=True)
print("git status with FIXED .gitignore:\n" + r.stdout)
